/**
 * Build the zero-install CLI bundle committed in dist/:
 *   dist/slidecraft.mjs  — every pure-JS dependency inlined (zod, yaml, commander,
 *                          fontkit, pdfkit, pptxgenjs, jszip)
 *   dist/resvg.wasm      — the PNG rasteriser
 * Fonts stay in fonts/ and are resolved relative to the package root at runtime.
 * CI runs this and fails on `git diff --exit-code dist/`.
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'dist');
mkdirSync(out, { recursive: true });

await build({
  entryPoints: [join(root, 'src/cli/main.ts')],
  outfile: join(out, 'slidecraft.mjs'),
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  legalComments: 'none',
  sourcemap: false,
  minify: false,
  banner: {
    js: [
      '// SlideCraft CLI bundle — generated by scripts/bundle.mjs; do not edit.',
      "import { createRequire as __scCreateRequire } from 'node:module';",
      "import { fileURLToPath as __scToPath } from 'node:url';",
      "import { dirname as __scDirname } from 'node:path';",
      'const require = __scCreateRequire(import.meta.url);',
      'const __filename = __scToPath(import.meta.url);',
      'const __dirname = __scDirname(__filename);',
    ].join('\n'),
  },
  logLevel: 'warning',
  plugins: [
    {
      // pdfkit loads its 14 standard fonts through `require('#standard-fonts/X')`,
      // which a bundle cannot resolve. Rewrite to static imports of the ESM modules.
      name: 'pdfkit-standard-fonts',
      setup(b) {
        b.onLoad({ filter: /pdfkit[\\/]js[\\/]pdfkit\.node\.mjs$/ }, (args) => {
          let code = readFileSync(args.path, 'utf8');
          const names = new Set();
          code = code.replace(/require\$1\('#standard-fonts\/(\w+)'\)/g, (_m, n) => {
            names.add(n);
            return `__scStd_${n}`;
          });
          const imports = [...names]
            .map((n) => `import __scStd_${n} from './standard-fonts/${n}.mjs';`)
            .join('\n');
          return { contents: `${imports}\n${code}`, loader: 'js', resolveDir: dirname(args.path) };
        });
      },
    },
  ],
});

// PDF text extraction (pdf.js) is a separate file, loaded only when a PDF is ingested.
await build({
  entryPoints: [join(root, 'src/library/pdf-text.ts')],
  outfile: join(out, 'pdf-text.mjs'),
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  legalComments: 'none',
  sourcemap: false,
  minify: true,
  logLevel: 'warning',
  banner: {
    js: [
      '// SlideCraft PDF text module (pdf.js, Apache-2.0) — generated by scripts/bundle.mjs; do not edit.',
      "import { createRequire as __scCreateRequire } from 'node:module';",
      'const require = __scCreateRequire(import.meta.url);',
    ].join('\n'),
  },
});

copyFileSync(join(root, 'node_modules/@resvg/resvg-wasm/index_bg.wasm'), join(out, 'resvg.wasm'));

// Ensure the bundle is executable via `node dist/slidecraft.mjs` and as a bin.
const file = join(out, 'slidecraft.mjs');
const src = readFileSync(file, 'utf8');
if (!src.startsWith('#!')) writeFileSync(file, `#!/usr/bin/env node\n${src}`);
console.log('dist/slidecraft.mjs + dist/pdf-text.mjs + dist/resvg.wasm');
