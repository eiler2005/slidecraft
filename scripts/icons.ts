/**
 * Regenerates src/engine/icons.gen.ts: a curated subset of Tabler Icons (MIT) as path data
 * in the 24-unit grid. Only these icons enter the bundle; add a name here and rerun
 * `npm run icons` to make it available to `icon:` fields.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const NAMES = `
users user user-check user-search users-group briefcase building building-factory building-bank
building-store chart-bar chart-line chart-pie chart-dots chart-arrows-vertical trending-up
trending-down target bulb rocket shield-check shield lock settings tool tools code terminal-2
database cloud server cpu brain robot message messages mail phone calendar clock stopwatch
hourglass flag map map-pin world route compass currency-dollar currency-euro coin cash receipt
shopping-cart truck package box leaf heart heart-handshake star award trophy certificate school
check circle-check x alert-triangle info-circle search zoom-check eye file-text file-analytics
report-analytics clipboard-check list-check checklist puzzle link git-branch refresh
arrows-exchange arrow-right arrow-up-right adjustments presentation speakerphone plug bolt api
sitemap hierarchy stack-2 versions components network scale gauge device-laptop device-mobile
plane home microscope flask sparkles wand infinity lifebuoy layout-dashboard player-play run walk
`
  .trim()
  .split(/\s+/);

const root = join(import.meta.dirname, '..');
const pkg = join(root, 'node_modules/@tabler/icons');
const nodes = JSON.parse(readFileSync(join(pkg, 'tabler-nodes-outline.json'), 'utf8')) as Record<
  string,
  [string, Record<string, string>][]
>;
const version = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')).version as string;
const license = readFileSync(join(pkg, 'LICENSE'), 'utf8').trim();

const icons: Record<string, string> = {};
for (const name of [...new Set(NAMES)].sort()) {
  const list = nodes[name];
  if (!list) throw new Error(`Tabler has no outline icon "${name}"`);
  icons[name] = list
    .map(([tag, a]) => {
      if (tag !== 'path') throw new Error(`${name}: unsupported element <${tag}>`);
      return a.d!;
    })
    .join(' ');
}

const out = `// Generated by scripts/icons.ts from @tabler/icons ${version} — do not edit.
// Outline icons on a 24×24 grid, drawn with a 2-unit round stroke.
/*
${license}
*/

export const ICON_SOURCE = 'Tabler Icons ${version} (MIT)';

export const ICONS: Record<string, string> = ${JSON.stringify(icons, null, 2)};
`;
writeFileSync(join(root, 'src/engine/icons.gen.ts'), out);
console.log(`✔ ${Object.keys(icons).length} icons → src/engine/icons.gen.ts`);
