function cliDoc(): string {
  const program = buildProgram();
  let md = HEADER('CLI reference', 'src/cli/*.ts');
  md +=
    'Run from a clone with `node dist/slidecraft.mjs <command>` (zero install) or `npx tsx src/cli/main.ts <command>` during development. Every command accepts `--json`; when stdout is not a terminal, commands with structured results print JSON (the others ignore the flag and print plain text).\n\n';
  const walk = (cmd: Command, prefix: string) => {
    for (const c of cmd.commands) {
      const name = `${prefix} ${c.name()}`.trim();
      if (c.commands.length) {
        walk(c, name);
        continue;
      }
      md += `## \`${name}\`\n\n${c.description()}\n\n\`\`\`\n${c
        .helpInformation()
        .replace(/^Usage: /, 'Usage: slidecraft ')
        .trim()}\n\`\`\`\n\n`;
    }
  };
  walk(program, '');
  return md;
}

function catalog(): unknown {
  return {
    version: VERSION,
    layouts: LAYOUTS.map((l) => ({
      id: l.id,
      name: l.name,
      group: l.group,
      variants: l.variants,
      purpose: l.purpose,
      frame: l.frame,
    })),
    themes: loadThemes().map((t) => ({
      id: t.id,
      name: t.name,
      bestFor: t.bestFor,
      dark: t.dark,
      prefers: t.prefers,
    })),
    storylines: loadStorylines().map((s) => ({
      id: s.id,
      name: s.name,
      arc: s.arc,
      bestFor: s.bestFor,
      themes: s.themes,
      slots: s.sections.flatMap((x) => x.slots.map((y) => y.id)),
    })),
    engines: engines().map((e) => ({
      kind: e.kind,
      id: e.id,
      license: e.license,
      proprietary: !!e.proprietary,
      capabilities: e.capabilities,
    })),
  };
}

export async function generateDocs(): Promise<string[]> {
  const ref = join(DOCS_DIR, 'reference');
  mkdirSync(ref, { recursive: true });
  mkdirSync(SCHEMAS_DIR, { recursive: true });
  const opts = { target: 'draft-2020-12' as const, unrepresentable: 'any' as const };
  const files: Record<string, string> = {
    [join(ref, 'layouts.gen.md')]: layoutsDoc(),
    [join(ref, 'themes.gen.md')]: themesDoc(),
    [join(ref, 'storylines.gen.md')]: storylinesDoc(),
    [join(ref, 'engines.gen.md')]: await enginesDoc(),
    [join(ref, 'error-codes.gen.md')]: codesDoc(),
    [join(ref, 'cli.gen.md')]: cliDoc(),
    [join(SCHEMAS_DIR, 'deck.v1.json')]: `${JSON.stringify(deckJsonSchema(), null, 2)}\n`,
    [join(SCHEMAS_DIR, 'brief.v1.json')]:
      `${JSON.stringify(z.toJSONSchema(Brief, opts), null, 2)}\n`,
    [join(SCHEMAS_DIR, 'theme.v1.json')]:
      `${JSON.stringify(z.toJSONSchema(Theme, opts), null, 2)}\n`,
    [join(SCHEMAS_DIR, 'storyline.v1.json')]:
      `${JSON.stringify(z.toJSONSchema(Storyline, opts), null, 2)}\n`,
    [join(LIBRARY_DIR, 'catalog.json')]: `${JSON.stringify(catalog(), null, 2)}\n`,
  };
  for (const [p, c] of Object.entries(files)) writeFileSync(p, c);
  return Object.keys(files);
}
